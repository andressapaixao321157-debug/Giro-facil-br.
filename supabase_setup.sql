-- Giro Fácil BR: estrutura inicial do banco
-- Execute no Supabase > SQL Editor > New query.
-- Este script cria as tabelas usadas pelo index.html e políticas RLS básicas.

create table if not exists public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  criado_em timestamptz not null default now()
);

create table if not exists public.anuncios (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  titulo text not null,
  categoria text not null check (categoria in (
    'Carro', 'Moto', 'Caminhão', 'Imóvel para venda', 'Imóvel para aluguel'
  )),
  marca text,
  modelo text,
  ano integer,
  preco numeric(14,2) not null check (preco >= 0),
  descricao text,
  cidade text,
  estado text,
  fotos text[] not null default '{}',
  whatsapp text,
  status text not null default 'pendente' check (status in ('pendente','ativo','reprovado')),
  criado_em timestamptz not null default now()
);

alter table public.perfis enable row level security;
alter table public.anuncios enable row level security;

drop policy if exists "Usuário lê próprio perfil" on public.perfis;
create policy "Usuário lê próprio perfil"
on public.perfis for select to authenticated
using (id = auth.uid());

drop policy if exists "Usuário cria próprio perfil" on public.perfis;
create policy "Usuário cria próprio perfil"
on public.perfis for insert to authenticated
with check (id = auth.uid());

drop policy if exists "Usuário atualiza próprio perfil" on public.perfis;
create policy "Usuário atualiza próprio perfil"
on public.perfis for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

drop policy if exists "Público vê anúncios ativos" on public.anuncios;
create policy "Público vê anúncios ativos"
on public.anuncios for select to anon, authenticated
using (status = 'ativo');

drop policy if exists "Anunciante vê próprios anúncios" on public.anuncios;
create policy "Anunciante vê próprios anúncios"
on public.anuncios for select to authenticated
using (usuario_id = auth.uid());

drop policy if exists "Anunciante cria próprio anúncio" on public.anuncios;
create policy "Anunciante cria próprio anúncio"
on public.anuncios for insert to authenticated
with check (usuario_id = auth.uid() and status = 'pendente');

-- Importante:
-- Não há política pública para alterar status. A aprovação deve ser feita
-- por administrador em ambiente seguro, nunca expondo service_role no site.
